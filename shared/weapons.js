export function loadoutSlots(loadout, team = 'T') {
  const key = teamKey(team);
  return ['primary', 'secondary', 'melee', 'grenade'].map((slot) => {
    const index = weaponIndex(loadout?.[slot]);
    return index >= 0 && WEAPONS[index].slot === slot && allowedFor(WEAPONS[index], key)
      ? index
      : weaponIndex(DEFAULT_LOADOUTS[key][slot]);
  });
}

export function sanitizeLoadout(loadout, team) {
  const [primary, secondary, melee, grenade] = loadoutSlots(loadout, team);
  return {
    primary: WEAPONS[primary].id,
    secondary: WEAPONS[secondary].id,
    melee: WEAPONS[melee].id,
    grenade: WEAPONS[grenade].id,
  };
}
